    <div class="card-body prose">
        <h3>1. Données collectées</h3>
        <p>Kintai collecte les données suivantes : nom, prénom, adresse e-mail, code employé, horaires de travail,
        pointages, demandes de congé, et préférences utilisateur. Ces données sont nécessaires à la gestion
        des plannings et des ressources humaines.</p>

        <h3>2. Base légale du traitement</h3>
        <p>Le traitement des données est fondé sur l'exécution du contrat de travail et l'intérêt légitime
        de l'employeur à organiser et gérer les plannings.</p>

        <h3>3. Destinataires des données</h3>
        <p>Les données sont accessibles uniquement aux administrateurs et managers autorisés de l'organisation.
        Elles ne sont pas partagées avec des tiers sans consentement explicite.</p>

        <h3>4. Durée de conservation</h3>
        <p>Les données sont conservées pendant la durée de la relation contractuelle, puis archivées
        conformément aux obligations légales (5 ans pour les données de paie).</p>

        <h3>5. Vos droits</h3>
        <p>Conformément au RGPD, vous disposez des droits suivants :</p>
        <ul>
            <li>Droit d'accès — obtenir une copie de vos données</li>
            <li>Droit de rectification — corriger vos données inexactes</li>
            <li>Droit à l'effacement — demander la suppression de vos données</li>
            <li>Droit à la portabilité — recevoir vos données dans un format structuré</li>
            <li>Droit d'opposition — vous opposer au traitement de vos données</li>
        </ul>
        <p>Pour exercer vos droits, contactez l'administrateur de votre organisation.</p>

        <h3>6. Cookies</h3>
        <p>Kintai utilise des cookies de session strictement nécessaires au fonctionnement de l'application
        (authentification, session utilisateur). Aucun cookie de suivi ou de publicité n'est utilisé.</p>

        <h3>7. Sécurité</h3>
        <p>Les données sont transmises via HTTPS et stockées sur des serveurs sécurisés.
        L'accès aux données est protégé par authentification et contrôle d'accès basé sur les rôles.</p>

        <h3>8. Contact</h3>
        <p>Pour toute question relative à la protection des données, contactez l'administrateur
        de votre instance Kintai.</p>
